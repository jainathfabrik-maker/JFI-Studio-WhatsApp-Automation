import { escapeHtml } from './util.js';

/**
 * The page the WhatsApp template button opens. One self-contained HTML
 * document — no external fonts, scripts or stylesheets — so it renders fast
 * on a phone over a weak connection and needs no CSP exceptions.
 */
export function renderPackPage(pack) {
  const section = (title, bodyHtml) => `
      <section class="card">
        <h2>${escapeHtml(title)}</h2>
        ${bodyHtml}
      </section>`;

  const hashtags = pack.hashtags
    .map((tag) => `<span class="tag">${escapeHtml(tag)}</span>`)
    .join('');

  const shots = pack.shotList
    .map((shot, index) => `<li><span class="num">${index + 1}</span><span>${escapeHtml(shot)}</span></li>`)
    .join('');

  const onScreen = (pack.onScreenText ?? [])
    .map((line, index) => `<li><span class="num">${index + 1}</span><span>${escapeHtml(line)}</span></li>`)
    .join('');

  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width, initial-scale=1" />
<meta name="robots" content="noindex, nofollow" />
<title>JFI Studio content pack — ${escapeHtml(pack.dateLabel)}</title>
<style>
  :root {
    --ink: #1b1a17;
    --muted: #6b675f;
    --line: #e4e0d7;
    --paper: #faf8f4;
    --accent: #8a6a3b;
  }
  * { box-sizing: border-box; }
  body {
    margin: 0; padding: 24px 16px 56px;
    background: var(--paper); color: var(--ink);
    font: 16px/1.6 -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, "Helvetica Neue", Arial, sans-serif;
  }
  .wrap { max-width: 720px; margin: 0 auto; }
  header { border-bottom: 2px solid var(--ink); padding-bottom: 16px; margin-bottom: 24px; }
  .brand { font-size: 13px; letter-spacing: .18em; text-transform: uppercase; color: var(--accent); font-weight: 700; }
  h1 { font-size: 26px; line-height: 1.25; margin: 8px 0 6px; }
  .meta { color: var(--muted); font-size: 14px; }
  .card {
    background: #fff; border: 1px solid var(--line); border-radius: 10px;
    padding: 18px 18px 20px; margin-bottom: 14px;
  }
  .card h2 {
    font-size: 12px; letter-spacing: .14em; text-transform: uppercase;
    color: var(--muted); margin: 0 0 10px; font-weight: 700;
  }
  .hook { font-size: 22px; line-height: 1.35; font-weight: 700; margin: 0; }
  p { margin: 0; white-space: pre-wrap; }
  ul { margin: 0; padding: 0; list-style: none; }
  li { display: flex; gap: 12px; padding: 7px 0; border-top: 1px solid var(--line); }
  li:first-child { border-top: none; padding-top: 0; }
  .num {
    flex: 0 0 24px; height: 24px; border-radius: 50%;
    background: var(--paper); border: 1px solid var(--line);
    font-size: 12px; font-weight: 700; display: flex; align-items: center; justify-content: center;
  }
  .tag {
    display: inline-block; margin: 0 6px 6px 0; padding: 3px 10px;
    background: var(--paper); border: 1px solid var(--line); border-radius: 999px;
    font-size: 13px; color: var(--accent);
  }
  footer { margin-top: 28px; color: var(--muted); font-size: 12px; text-align: center; }
  @media (prefers-color-scheme: dark) {
    :root { --ink: #f2efe9; --muted: #a39e94; --line: #33312c; --paper: #16150f; --accent: #d8b483; }
    body { background: var(--paper); }
    .card { background: #1e1d17; }
  }
</style>
</head>
<body>
  <div class="wrap">
    <header>
      <div class="brand">JFI Studio · Bengaluru</div>
      <h1>Daily content pack</h1>
      <div class="meta">${escapeHtml(pack.dateLabel)} · Pillar: ${escapeHtml(pack.pillar)} · Generated by ${escapeHtml(pack.source)}</div>
    </header>

    ${section('Hook (max 12 words)', `<p class="hook">${escapeHtml(pack.hook)}</p>`)}
    ${section('Format and duration', `<p>${escapeHtml(pack.format)}</p>`)}
    ${section('Concept', `<p>${escapeHtml(pack.concept ?? '')}</p>`)}
    ${section('Caption — ready to publish', `<p>${escapeHtml(pack.caption)}</p>`)}
    ${section('Call to action', `<p>${escapeHtml(pack.cta)}</p>`)}
    ${section('Hashtags', `<div>${hashtags}</div>`)}
    ${section('Shot list', `<ul>${shots}</ul>`)}
    ${section('On-screen text', `<ul>${onScreen}</ul>`)}
    ${section('Tracking', `<p>Metric: ${escapeHtml(pack.tracking?.metric ?? '—')}<br />UTM campaign: ${escapeHtml(pack.tracking?.utmCampaign ?? '—')}</p>`)}
    ${section('Publish time', `<p>${escapeHtml(pack.publishTimeIST)}</p>`)}

    <footer>
      Pack ${escapeHtml(pack.id)} · ${escapeHtml(pack.date)}<br />
      Private link. Do not forward.
    </footer>
  </div>
</body>
</html>`;
}
